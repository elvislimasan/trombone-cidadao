-- Marcos: catalogo publico, escrita de quem responde pela cidade.
drop policy if exists city_collectibles_select on public.city_collectibles;
create policy city_collectibles_select on public.city_collectibles
  for select using (true);

drop policy if exists city_collectibles_gestor_write on public.city_collectibles;
create policy city_collectibles_gestor_write on public.city_collectibles
  for all to authenticated
  using (
    public.is_admin(auth.uid())
    or public.is_master(auth.uid())
    or public.is_ambassador_of(auth.uid(), city_id)
  )
  with check (
    public.is_admin(auth.uid())
    or public.is_master(auth.uid())
    or public.is_ambassador_of(auth.uid(), city_id)
  );

-- Visitas: SO O DONO, em tudo.
--
-- Nem admin le. Nao e desconfianca da moderacao: e que nao existe pergunta
-- legitima da moderacao sobre onde uma pessoa passeou — e uma tabela que
-- responde essa pergunta acaba respondendo-a.
drop policy if exists collectible_discoveries_own on public.collectible_discoveries;
create policy collectible_discoveries_own on public.collectible_discoveries
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- Consentimento: so o dono ve e escreve o proprio.
drop policy if exists sensing_consent_own on public.sensing_consent;
create policy sensing_consent_own on public.sensing_consent
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- Candidatos: so o dono, e so os que ainda estao na janela.
--
-- O filtro de data na PROPRIA policy e a segunda metade da retencao: mesmo que
-- a limpeza nao tenha rodado, o que venceu ja nao existe para ninguem.
drop policy if exists sensing_candidates_own on public.sensing_candidates;
create policy sensing_candidates_own on public.sensing_candidates
  for all to authenticated
  using (
    user_id = auth.uid()
    and ocorreu_em >= now() - interval '7 days'
  )
  with check (user_id = auth.uid());

-- Sugestoes: cada um grava a propria; ninguem le linha a linha.
--
-- A avaliacao sai de `assist_avaliacao`, que e SECURITY DEFINER e devolve so
-- totais. Abrir a leitura linha a linha diria quais categorias uma pessoa
-- especifica costuma registrar — que e perfil de comportamento, e nao e
-- necessario para nada aqui.
drop policy if exists assist_suggestions_insert_own on public.assist_suggestions;
create policy assist_suggestions_insert_own on public.assist_suggestions
  for insert to authenticated
  with check (user_id = auth.uid());

drop policy if exists assist_suggestions_admin_select on public.assist_suggestions;
create policy assist_suggestions_admin_select on public.assist_suggestions
  for select to authenticated
  using (public.is_admin(auth.uid()) or public.is_master(auth.uid()));

