-- PARTE 4 — NOTIFICACAO POR MUDANCA REAL DE ESTADO
-- ═══════════════════════════════════════════════════════════════════════════

-- Uma etapa oficial nova e a definicao de mudanca real de estado: alguem fora
-- do app fez alguma coisa. Vai para todos os participantes, pelo mesmo motivo
-- da 199 — quem confirmou em campo fez o trabalho que sustenta a verificacao.
--
-- E DELIBERADAMENTE CAUTELOSA NO TEXTO
--
-- "Encaminhada ao orgao" nao pode chegar no aparelho parecendo "resolvido". O
-- corpo diz o que falta, nao o que foi conquistado.
create or replace function public.notificar_etapa_oficial()
returns trigger
language plpgsql
security definer
set search_path = public, extensions
as $fn$
declare
  v_onde   text;
  v_titulo text;
  v_corpo  text;
begin
  select coalesce(nullif(btrim(r.address), ''), nullif(btrim(r.title), ''),
                  'Uma bronca que voce acompanha')
    into v_onde
  from public.reports r where r.id = new.report_id;

  v_titulo := case new.etapa
    when 'encaminhada' then 'Encaminhada ao orgao responsavel'
    when 'recebida'    then 'O orgao confirmou o recebimento'
    when 'programada'  then 'Entrou na programacao do orgao'
    when 'executada'   then 'O orgao informou execucao'
    when 'recusada'    then 'O orgao recusou a solicitacao'
  end;

  v_corpo := case new.etapa
    when 'executada'
      then left(v_onde, 80) || '. Ninguem confirmou no local ainda — se voce passar por la, diga como esta.'
    when 'recusada'
      then left(v_onde, 80) || '. Motivo: ' || coalesce(nullif(btrim(new.observacao), ''), 'nao informado') || '.'
    else
      left(v_onde, 80) || '. Encaminhar nao e resolver: a execucao depende do orgao publico.'
  end;

  insert into public.notifications (user_id, type, title, message, link, report_id, is_read, created_at)
  select p.user_id, 'status_update', v_titulo, v_corpo,
         '/bronca/' || new.report_id, new.report_id, false, now()
  from public.report_participants(new.report_id) p;

  return new;
end;
$fn$;

