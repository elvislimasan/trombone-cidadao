-- Quem pode falar em nome do encaminhamento desta bronca.
--
-- Nao reaproveita `can_manage_city_events` de proposito: aquela funcao responde
-- "pode gerir acontecimentos da cidade", e um nome que responde uma pergunta
-- sendo usado para outra e como as duas divergem em silencio quando uma delas
-- mudar. A regra e a mesma hoje; a pergunta nao e.
create or replace function public.pode_registrar_etapa_oficial(p_user uuid, p_report_id uuid)
returns boolean
language plpgsql
stable
security definer
set search_path = public, extensions
as $fn$
declare
  v_city_id bigint;
begin
  if p_user is null or p_report_id is null then return false; end if;
  if public.is_admin(p_user) or public.is_master(p_user) then return true; end if;

  select city_id into v_city_id from public.reports where id = p_report_id;
  if v_city_id is null then return false; end if;

  return public.is_ambassador_of(p_user, v_city_id);
end;
$fn$;

comment on function public.pode_registrar_etapa_oficial(uuid, uuid) is
  'Admin, master ou embaixador da cidade da bronca. Quem fala com a prefeitura e quem registra o que ela respondeu.';

-- As quatro etapas que o app nao tem como deduzir.
--
-- POR QUE NAO DA PARA DERIVAR DE `status`
--
-- `reports.status` tem quatro valores (pending, in-progress, resolved,
-- duplicate) e nenhum deles distingue "o oficio saiu" de "a prefeitura
-- respondeu" de "entrou no cronograma". A barra antiga tratava 'in-progress'
-- como "Em execucao" e marcava "Em analise" como concluida por inferencia —
-- ou seja, afirmava duas coisas que ninguem havia dito.
--
-- `recusada` NAO e uma quinta etapa do caminho: e o fim de um. Fica na mesma
-- tabela porque e o mesmo fato — o que o orgao respondeu — e porque separa-la
-- faria a tela precisar unir duas fontes so para descobrir se ainda ha o que
-- esperar.
--
-- APPEND-ONLY, COMO A 206
--
-- Sem policy de update e sem policy de delete. Uma etapa registrada por engano
-- e corrigida por outra etapa; apagar sumiria com a historia, que e exatamente
-- o que uma linha do tempo com proveniencia existe para impedir.
--
-- `ocorreu_em` E DIFERENTE DE `created_at`
--
-- O oficio saiu dia 3 e o embaixador registrou dia 11. Uma coluna so obrigaria
-- a escolher entre mentir sobre o fato e mentir sobre o registro. `ocorreu_em`
-- e a hora do FATO e e o que a linha do tempo ordena; `created_at` e a hora do
-- registro e e o que a auditoria le. Mesma distincao da 194.

create table if not exists public.report_official_steps (
  id            bigint generated by default as identity primary key,
  report_id     uuid not null references public.reports(id) on delete cascade,

  etapa         text not null,
  orgao         text,
  protocolo     text,
  observacao    text,

  ocorreu_em    timestamptz not null default now(),

  registrado_por      uuid references public.profiles(id) on delete set null,
  registrado_por_papel text,

  created_at    timestamptz not null default now(),

  constraint report_official_steps_etapa_valida check (etapa in (
    'encaminhada', 'recebida', 'programada', 'executada', 'recusada'
  )),
  -- Recusa sem motivo e a mesma falha que a rejeicao muda de atualizacao: o
  -- cidadao fica sabendo que nao vai acontecer e nao fica sabendo por que.
  constraint report_official_steps_recusa_tem_motivo check (
    etapa <> 'recusada' or length(btrim(coalesce(observacao, ''))) > 0
  )
);

-- Fato no futuro nao e fato.
--
-- Gatilho e nao CHECK, pelo mesmo motivo da 193: `now()` num CHECK e avaliado
-- na insercao e nunca mais, entao a restricao mente sobre o que garante — e um
-- dump e restore reavalia tudo com o relogio de hoje e recusa linhas validas.
--
-- Um dia de folga porque relogio de celular adianta, e recusar o registro de um
-- oficio por causa disso seria perder o dado para proteger o formato.
create or replace function public.etapa_oficial_sem_futuro()
returns trigger
language plpgsql
as $fn$
begin
  if new.ocorreu_em is null or new.ocorreu_em > now() + interval '1 day' then
    new.ocorreu_em := now();
  end if;
  return new;
end;
$fn$;

drop trigger if exists a_etapa_oficial_sem_futuro on public.report_official_steps;
create trigger a_etapa_oficial_sem_futuro
before insert on public.report_official_steps
for each row execute function public.etapa_oficial_sem_futuro();

