comment on function public.notificar_etapa_oficial() is
  'Avisa os participantes quando o orgao mexe. O texto nunca deixa "encaminhada" soar como "resolvida".';

-- ── A correcao de texto da resolucao ────────────────────────────────────────
--
-- A 199 escreveu "Voce fez isso acontecer." A secao 36.5 do plano pede o
-- contrario, e a razao e de honestidade, nao de tom: uma bronca resolvida
-- depois prova que a pessoa registrou, verificou e acompanhou. Nao prova,
-- sozinha, que ela causou o conserto — quem consertou foi quem foi la com a
-- maquina.
--
-- Prometer causalidade individual e o tipo de exagero que funciona uma vez e
-- corroi a credibilidade do placar inteiro depois. Espelha `fraseDaResolucao`
-- em src/lib/impact.js, que muda junto.
create or replace function public.notificar_resolucao()
returns trigger
language plpgsql
security definer
set search_path = public, extensions
as $fn$
declare
  v_total integer;
  v_onde  text;
begin
  if new.status is not distinct from old.status or new.status <> 'resolved' then
    return new;
  end if;

  select count(*) into v_total from public.report_participants(new.id);
  v_onde := coalesce(nullif(trim(new.address), ''), nullif(trim(new.title), ''),
                     'Um problema que voce acompanhava');

  insert into public.notifications (user_id, type, title, message, link, is_read, created_at)
  select
    p.user_id,
    'status_update',
    left(v_onde, 80) || ' foi resolvido',
    case
      when v_total <= 1 then 'Voce contribuiu para registrar, verificar e acompanhar esta solucao.'
      when v_total = 2  then 'Voce e mais 1 pessoa acompanharam este problema ate o fim.'
      else 'Voce e mais ' || (v_total - 1) || ' pessoas acompanharam este problema ate o fim.'
    end,
    '/bronca/' || new.id,
    false,
    now()
  from public.report_participants(new.id) p;

  return new;
end;
