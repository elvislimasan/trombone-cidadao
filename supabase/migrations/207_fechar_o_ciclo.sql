-- 207_fechar_o_ciclo.sql
--
-- Fase 1 do roadmap revisado (secao 36.14 do plano de gamificacao): fazer o
-- usuario enxergar o efeito da participacao.
--
-- Tres buracos, tres partes:
--
--   1. a linha do tempo nao tinha onde guardar o que o ORGAO fez;
--   2. uma atualizacao rejeitada sumia da tela sem dizer por que;
--   3. depois de 28 dias ninguem perguntava como a rua ficou.
--
-- E uma correcao de texto que nao custa coluna nenhuma: a notificacao de
-- resolucao diz "Voce fez isso acontecer", e a secao 36.5 pede o contrario —
-- uma resolucao posterior prova participacao no acompanhamento, nao causalidade
-- individual.
--
-- POR QUE report_timeline NAO E REAPROVEITADA
--
-- Ela existe, e lida por quatro telas e nunca foi escrita por nenhuma. Nao tem
-- coluna de etapa nem de proveniencia — `ReportProgress.jsx` documenta isso em
-- comentario e cai no ultimo registro como aproximacao de data. Encaixar
-- proveniencia numa tabela cujo formato ninguem conhece, com linhas historicas
-- de origem desconhecida, seria construir sobre chao que nao da para inspecionar.
-- Ela fica onde esta, intocada; o que este arquivo cria e uma tabela nova, com
-- proposito estreito: as quatro etapas que so um terceiro conhece.
--
-- O RESTO DA LINHA DO TEMPO CONTINUA DERIVADO
--
-- Registro sai de `reports`, moderacao sai de `moderation_status`, validacao e
-- verificacao saem de `report_updates` via a regra da 199. Mesma escolha da 169,
-- 198 e 199: nada de estado gravado onde o dado ja responde. `src/lib/
-- reportTimeline.js` monta a linha inteira a partir dessas fontes, e
-- `src/test/reportTimeline.test.mjs` guarda as regras.
--
-- AS POLICIES ESTAO AQUI, DE PROPOSITO
--
-- Mesma preocupacao da 206: neste projeto as policies moram no painel do
-- Supabase e nao no git, entao toda tabela nova vira regra invisivel ao codigo.
-- Toda policy das duas tabelas novas esta escrita neste arquivo.

