-- PARTE 2 — REJEICAO QUE EXPLICA
-- ═══════════════════════════════════════════════════════════════════════════
--
-- HOJE A ATUALIZACAO REJEITADA SIMPLESMENTE DESAPARECE
--
-- `ModerationPage` grava `status = 'rejected'` e manda uma notificacao com uma
-- frase fixa: "nao foi aprovada por nao cumprir as diretrizes". Qual diretriz,
-- nao diz. `ReportPage` filtra a linha da lista — inclusive para o proprio
-- autor — e `ReportUpdates.jsx` chega a calcular `isRejected` e nunca usa.
--
-- Do lado de quem enviou, a experiencia inteira e: mandei uma foto, ganhei um
-- aviso generico, a atualizacao sumiu e nao ha o que fazer a respeito.
--
-- A bronca ja resolveu isso ha tempos — `reports` tem rejection_title,
-- rejection_description e rejected_at, e a moderacao exige os dois textos. A
-- atualizacao ficou para tras. Esta parte iguala as duas.
--
-- MOTIVO ESTRUTURADO, NAO SO TEXTO LIVRE
--
-- O texto livre resolve o caso individual e nao resolve o produto: nao da para
-- contar quantas rejeicoes sao de foto ilegivel, e sem contar nao da para
-- consertar o formulario que produz foto ilegivel. O codigo estruturado e o que
-- torna a rejeicao um dado de qualidade em vez de uma frase.
--
-- Os codigos espelham MOTIVOS_DE_REJEICAO em src/lib/reportRejection.js.

alter table public.report_updates
  add column if not exists rejection_reason text,
  add column if not exists rejection_note   text,
  add column if not exists rejected_at      timestamptz,
  add column if not exists rejected_by      uuid references public.profiles(id) on delete set null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'report_updates_motivo_de_rejeicao_valido'
      and conrelid = 'public.report_updates'::regclass
  ) then
    -- NOT VALID: as linhas rejeitadas antes desta migracao nao tem motivo, e
    -- apagar ou inventar o motivo delas seria reescrever o passado por causa de
    -- um criterio novo. A regra vale para toda linha nova.
    alter table public.report_updates
      add constraint report_updates_motivo_de_rejeicao_valido
      check (
        rejection_reason is null or rejection_reason in (
          'fora_do_local', 'sem_evidencia', 'evidencia_ilegivel', 'nao_corresponde',
          'duplicada', 'conteudo_improprio', 'dado_pessoal', 'outro'
        )
      ) not valid;
  end if;
end $$;

comment on column public.report_updates.rejection_reason is
  'Codigo do motivo. Espelha MOTIVOS_DE_REJEICAO em src/lib/reportRejection.js; existe para a rejeicao virar dado de qualidade, nao so frase.';
comment on column public.report_updates.rejection_note is
  'O que o moderador escreveu para esta pessoa. E a metade que ensina.';

-- A notificacao da rejeicao, com o motivo dentro.
--
-- Sai do cliente e vem para o banco pelo mesmo motivo da 199: hoje quem escreve
-- a notificacao e `ModerationPage`, e um segundo lugar que rejeite atualizacao
-- (uma tela de embaixador, um script) esquece de avisar sem que nada acuse.
--
-- Nao substitui o texto do moderador: o `rejection_note` e o que a pessoa mais
-- precisa ler, e o codigo do motivo entra so quando nao ha nota.
create or replace function public.notificar_rejeicao_de_atualizacao()
returns trigger
language plpgsql
security definer
set search_path = public, extensions
as $fn$
declare
  v_titulo text;
  v_motivo text;
begin
  if new.status <> 'rejected' or coalesce(old.status, '') = 'rejected' then
    return new;
  end if;
  if new.author_id is null then
    return new;
  end if;

  select title into v_titulo from public.reports where id = new.report_id;

  v_motivo := coalesce(
    nullif(btrim(new.rejection_note), ''),
    case new.rejection_reason
      when 'fora_do_local'      then 'A foto ou o relato nao parece ser do local da bronca.'
      when 'sem_evidencia'      then 'Faltou evidencia do que voce descreveu.'
      when 'evidencia_ilegivel' then 'A foto nao permite ver o que foi relatado.'
      when 'nao_corresponde'    then 'O que foi relatado nao corresponde ao problema desta bronca.'
      when 'duplicada'          then 'Esta mesma informacao ja havia sido enviada.'
      when 'conteudo_improprio' then 'O conteudo enviado nao cumpre as diretrizes.'
      when 'dado_pessoal'       then 'A imagem ou o texto expunha dado pessoal de alguem.'
      else 'A atualizacao nao foi aprovada.'
    end
  );

  insert into public.notifications (user_id, type, title, message, link, report_id, is_read, created_at)
  values (
    new.author_id,
    'status_update',
    'Sua atualizacao nao foi publicada',
    v_motivo || ' Voce pode corrigir e reenviar em "' || coalesce(v_titulo, 'a bronca') || '".',
    '/bronca/' || new.report_id,
    new.report_id,
    false,
    now()
  );

  return new;
end;
$fn$;

drop trigger if exists on_report_update_rejeitada on public.report_updates;
create trigger on_report_update_rejeitada
after update of status on public.report_updates
for each row execute function public.notificar_rejeicao_de_atualizacao();

comment on function public.notificar_rejeicao_de_atualizacao() is
  'Avisa quem enviou, com o motivo e o caminho de correcao. Uma rejeicao bem explicada preserva confianca; uma rejeicao silenciosa gasta.';

-- ── A atualizacao rejeitada volta a ser visivel PARA QUEM A ENVIOU ──────────
--
-- Precisa existir no banco, nao so na tela: `ReportPage` esconde a linha, mas
-- se a policy de select tambem escondesse, o cliente nunca teria o que mostrar.
-- Para os outros ela continua invisivel — uma rejeicao e uma conversa entre a
-- moderacao e quem enviou, nao um aviso publico sobre a pessoa.
--
-- Esta policy e ADITIVA: policies de select se somam por OR, entao a policy que
-- ja existe (e que mora no painel) continua valendo para todo o resto.
drop policy if exists report_updates_autor_ve_a_propria_rejeitada on public.report_updates;
create policy report_updates_autor_ve_a_propria_rejeitada on public.report_updates
  for select to authenticated
  using (author_id = auth.uid());

-- ═══════════════════════════════════════════════════════════════════════════
-- PARTE 3 — A REVISITA DE 28 DIAS
-- ═══════════════════════════════════════════════════════════════════════════
--
-- "Faz 28 dias que voce registrou este problema. Como ele esta agora?"
--
-- POR QUE 28 DIAS, E POR QUE OPT-IN
--
-- E o intervalo do FixMyStreet, e a escolha por tras dele importa mais que o
-- numero: e uma alternativa a exigir uso diario. O produto pergunta uma vez,
-- por bronca, e a pessoa decide se quer ser perguntada de novo. Participacao
-- episodica e legitima (principio 13); o app nao fabrica culpa.
--
-- ESTA TABELA NAO GUARDA A RESPOSTA DE CAMPO
--
-- "Continua igual", "melhorou" e "foi resolvido" viram linha de
-- `report_updates`, que e onde toda observacao de campo mora — e assim a
-- resposta da revisita passa pelas MESMAS regras: moderacao, limite semanal,
-- quorum da 199, credito de Impacto da 198. Uma segunda tabela de observacao
-- seria uma segunda verdade sobre o estado da rua.
--
-- O que fica aqui e so o que a `report_updates` nao sabe responder: a quem
-- perguntamos, quando, o que a pessoa respondeu ao convite (inclusive "nao
-- consigo verificar", que nao gera observacao nenhuma) e se ela quer o proximo
-- lembrete.

create table if not exists public.report_revisits (
  id                bigint generated by default as identity primary key,
  report_id         uuid not null references public.reports(id) on delete cascade,
  user_id           uuid not null references public.profiles(id) on delete cascade,

  perguntada_em     timestamptz not null default now(),
  respondida_em     timestamptz,
  resposta          text,

  -- Null = ainda nao disse. False = pediu para nao perguntar de novo NESTA
  -- bronca. A ausencia de resposta nao pode virar "nao quer": quem ignorou um
  -- convite nao optou por nada.
  quer_lembrete     boolean,

  report_update_id  uuid references public.report_updates(id) on delete set null,

  created_at        timestamptz not null default now(),

  constraint report_revisits_resposta_valida check (
    resposta is null or resposta in (
      'igual', 'piorou', 'melhorou', 'resolvido', 'nao_consigo_verificar'
    )
  ),
  constraint report_revisits_resposta_tem_data check (
    (resposta is null) = (respondida_em is null)
  )
);

comment on table public.report_revisits is
  'Convite de microatualizacao apos 28 dias. Guarda o CONVITE; a observacao de campo vira report_updates, para passar pelas mesmas regras.';
comment on column public.report_revisits.quer_lembrete is
  'Null = nao disse. False = nao perguntar de novo nesta bronca. Ausencia de resposta nunca vira recusa.';

-- Uma pergunta aberta por pessoa e por bronca. Sem isto, abrir a tela duas
-- vezes cria dois convites e a mesma pessoa e perguntada em dobro.
create unique index if not exists report_revisits_uma_aberta_por_pessoa
  on public.report_revisits (report_id, user_id)
  where respondida_em is null;

create index if not exists report_revisits_por_pessoa_idx
  on public.report_revisits (user_id, perguntada_em desc);

-- Quem deve ser convidado agora.
--
-- Devolve so o que a tela precisa para montar o convite. As condicoes sao todas
-- de exclusao, e cada uma existe por um motivo:
--
--   • bronca aberta — perguntar "como esta?" sobre algo ja verificado e ruido;
--   • aprovada — bronca recusada nao tem o que revisitar;
--   • 28 dias desde o ULTIMO fato conhecido, nao desde o registro: uma bronca
--     atualizada ontem nao esta parada ha 28 dias;
--   • ninguem ja convidado nesta bronca com convite em aberto;
--   • ninguem que pediu para nao ser perguntado de novo AQUI.
create or replace function public.revisitas_pendentes(p_user uuid, p_limite integer default 3)
returns table (
  report_id    uuid,
  titulo       text,
  endereco     text,
  registrada_em timestamptz,
  dias_parada  integer
)
language sql
stable
security definer
set search_path = public, extensions
as $fn$
  select
    r.id,
    r.title,
    r.address,
    r.created_at,
    extract(day from now() - greatest(
      r.created_at,
      coalesce((select max(u.created_at) from public.report_updates u
                where u.report_id = r.id and coalesce(u.status,'') <> 'rejected'), r.created_at)
    ))::integer
  from public.reports r
  where r.author_id = p_user
    and r.status in ('pending', 'in-progress')
    and coalesce(r.moderation_status, 'approved') = 'approved'
    and greatest(
      r.created_at,
      coalesce((select max(u.created_at) from public.report_updates u
                where u.report_id = r.id and coalesce(u.status,'') <> 'rejected'), r.created_at)
    ) < now() - interval '28 days'
    and not exists (
      select 1 from public.report_revisits rv
      where rv.report_id = r.id
        and rv.user_id = p_user
        and (rv.respondida_em is null or rv.quer_lembrete is false)
    )
  order by r.created_at
  limit greatest(1, least(coalesce(p_limite, 3), 10));
$fn$;

comment on function public.revisitas_pendentes(uuid, integer) is
  'Broncas do proprio usuario paradas ha 28 dias, sem convite em aberto e sem recusa de lembrete. Opt-in por bronca.';

grant execute on function public.revisitas_pendentes(uuid, integer) to authenticated;

