-- Sugestoes: leitura publica (a cobertura e informacao da cidade), insercao do
-- proprio usuario, e NENHUMA policy de update para quem nao modera.
--
-- A ausencia de update para o autor e deliberada: sugestao editavel depois de
-- enviada e sugestao que muda de resposta quando alguem discorda dela.
drop policy if exists pavement_suggestions_select on public.pavement_suggestions;
create policy pavement_suggestions_select on public.pavement_suggestions
  for select using (true);

drop policy if exists pavement_suggestions_insert on public.pavement_suggestions;
create policy pavement_suggestions_insert on public.pavement_suggestions
  for insert to authenticated
  with check (user_id = auth.uid());

drop policy if exists pavement_suggestions_moderacao_update on public.pavement_suggestions;
create policy pavement_suggestions_moderacao_update on public.pavement_suggestions
  for update to authenticated
  using (
    public.is_admin(auth.uid())
    or public.is_master(auth.uid())
    or exists (
      select 1 from public.pavement_streets s
      where s.id = street_id
        and s.city_id is not null
        and public.is_ambassador_of(auth.uid(), s.city_id)
    )
  )
  with check (true);

-- Metas: o publico ve o que nao e rascunho — o relatorio publico so serve se
-- for publico. Gestao e de quem responde pela cidade.
drop policy if exists community_goals_select on public.community_goals;
create policy community_goals_select on public.community_goals
  for select using (
    status <> 'rascunho'
    or public.is_admin(auth.uid())
    or public.is_master(auth.uid())
    or public.is_ambassador_of(auth.uid(), city_id)
  );

drop policy if exists community_goals_gestor_write on public.community_goals;
create policy community_goals_gestor_write on public.community_goals
  for all to authenticated
  using (
    public.is_admin(auth.uid())
    or public.is_master(auth.uid())
    or public.is_ambassador_of(auth.uid(), city_id)
  )
  with check (
    public.is_admin(auth.uid())
    or public.is_master(auth.uid())
    or public.is_ambassador_of(auth.uid(), city_id)
  );

-- Mutiroes: mesma logica. Rascunho e do organizador e de quem modera; publicado
-- e convite, e convite e publico.
drop policy if exists mutiroes_select on public.mutiroes;
create policy mutiroes_select on public.mutiroes
  for select using (
    status in ('publicado', 'encerrado')
    or organizador_id = auth.uid()
    or public.is_admin(auth.uid())
    or public.is_master(auth.uid())
    or public.is_ambassador_of(auth.uid(), city_id)
  );

drop policy if exists mutiroes_gestor_write on public.mutiroes;
create policy mutiroes_gestor_write on public.mutiroes
  for all to authenticated
  using (
    organizador_id = auth.uid()
    or public.is_admin(auth.uid())
    or public.is_master(auth.uid())
    or public.is_ambassador_of(auth.uid(), city_id)
  )
  with check (
    organizador_id = auth.uid()
    or public.is_admin(auth.uid())
    or public.is_master(auth.uid())
    or public.is_ambassador_of(auth.uid(), city_id)
  );

