-- O papel com que a pessoa age, para gravar em created_by_role/resolved_by_role.
--
-- Nao e enfeite de auditoria: a secao 12 do plano manda notificar "o
-- administrador, o embaixador responsavel, ou ambos, conforme a regra". Sem
-- saber com que papel a linha foi criada, essa escolha nao tem como existir
-- depois.
create or replace function public.city_event_role(p_user uuid, p_city_id bigint)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select case
    when p_user is null then null
    when public.is_master(p_user) then 'master'
    when public.is_admin(p_user) then 'admin'
    when public.is_ambassador_of(p_user, p_city_id) then 'ambassador'
    else null
  end;
$$;

-- Pode gerir acontecimentos desta cidade?
create or replace function public.can_manage_city_events(p_user uuid, p_city_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.city_event_role(p_user, p_city_id) is not null;
$$;

-- As areas pedidas cabem no escopo de quem esta publicando?
--
-- Admin e master passam direto. Embaixador SEM linhas em ambassador_areas
-- tambem — e a cidade inteira dele, como sempre foi. Embaixador COM bairros
-- designados so passa se cada area pedida estiver dentro deles.
create or replace function public.city_event_scope_ok(p_user uuid, p_city_id bigint, p_areas jsonb)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_designados integer;
  v_area       jsonb;
  v_tipo       text;
  v_id         uuid;
begin
  if p_user is null then return false; end if;
  if public.is_admin(p_user) or public.is_master(p_user) then return true; end if;
  if not public.is_ambassador_of(p_user, p_city_id) then return false; end if;

  select count(*) into v_designados
  from public.ambassador_areas
  where user_id = p_user and city_id = p_city_id;

  if v_designados = 0 then return true; end if;

  -- O apelido da coluna e explicito (`as t(item)`) porque `select value from
  -- jsonb_array_elements(...)` depende do nome do parametro OUT da funcao, e
  -- `... x` sozinho depende de como o Postgres resolve apelido de tabela sobre
  -- funcao escalar. Nomear a coluna tira as duas duvidas.
  for v_area in select t.item from jsonb_array_elements(coalesce(p_areas, '[]'::jsonb)) as t(item)
  loop
    v_tipo := v_area->>'area_type';

    -- Quem tem bairro designado nao publica para a cidade inteira: seria
    -- exatamente o escopo que a designacao existe para tirar.
    if v_tipo = 'city' then return false; end if;

    v_id := nullif(v_area->>'area_id', '')::uuid;
    if v_id is null then return false; end if;

    if v_tipo = 'neighborhood' then
      if not exists (
        select 1 from public.ambassador_areas aa
        where aa.user_id = p_user and aa.city_id = p_city_id
          and aa.area_type = 'neighborhood' and aa.area_id = v_id
      ) then
        return false;
      end if;

    elsif v_tipo = 'street' then
      -- Uma rua so cabe no escopo se o bairro dela couber. Rua sem bairro
      -- cadastrado nao cabe em nenhum: nao da para provar que cabe.
      if not exists (
        select 1
        from public.pavement_streets s
        join public.ambassador_areas aa
          on aa.area_type = 'neighborhood' and aa.area_id = s.bairro_id
        where s.id = v_id
          and aa.user_id = p_user and aa.city_id = p_city_id
      ) then
        return false;
      end if;

    else
      return false;
    end if;
  end loop;

  return true;
end;
$$;

