-- ── 1.1 O acontecimento ─────────────────────────────────────────────────────
--
-- ESTADOS, E O QUE `EXTENDED` E `REOPENED` REALMENTE SAO
--
-- O plano desenha ACTIVE -> EXTENDED -> ACTIVE e RESOLVED -> REOPENED ->
-- ACTIVE. Os dois voltam para ACTIVE no passo seguinte, ou seja: nao sao
-- estados de repouso, sao ACONTECIMENTOS na linha do tempo. Guardados como
-- status, seriam valores em que nenhuma consulta jamais encontra linha, e toda
-- tela precisaria tratar 'extended' como sinonimo de 'active'.
--
-- Eles entram como `type` em city_event_updates, que e onde a historia mora.
--
-- `awaiting_confirmation` E estado de repouso, e responde a regra 4 do plano
-- ("a previsao vencida nao encerra automaticamente"): a previsao passou, o
-- responsavel foi avisado, e ninguem ainda disse se normalizou. Sem ele, um
-- evento vencido fica indistinguivel de um em dia — e a cidade le
-- "previsao: hoje ate 18h" as 22h.

create table if not exists public.city_events (
  id                  bigint generated by default as identity primary key,
  city_id             bigint not null references public.cities(id) on delete cascade,

  type                text not null,
  title               text not null,
  description         text,

  severity            text not null default 'warning',
  status              text not null default 'active',

  started_at          timestamptz not null default now(),
  estimated_end_at    timestamptz,
  resolved_at         timestamptz,

  source_name         text,
  source_url          text,

  created_by          uuid references public.profiles(id) on delete set null,
  created_by_role     text,

  resolved_by         uuid references public.profiles(id) on delete set null,
  resolved_by_role    text,

  -- Quantas vezes o evento ja foi dado como resolvido. E o "ciclo" da regra do
  -- plano: uma confirmacao ativa por pessoa POR CICLO. Reabrir soma 1 e a
  -- enquete recomeca do zero, sem apagar as respostas do ciclo anterior — que
  -- sao justamente a prova de que a reabertura fazia sentido.
  confirmation_cycle  integer not null default 0,

  -- Quando o responsavel foi avisado de que a previsao venceu. Existe para a
  -- varredura ser idempotente: rodar de novo nao reavisa ninguem.
  overdue_notified_at timestamptz,

  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),

  constraint city_events_type_valido check (type in (
    'water_outage', 'power_outage', 'road_block', 'traffic', 'weather',
    'public_transport', 'health', 'construction', 'event', 'public_notice', 'other'
  )),
  constraint city_events_severity_valida check (severity in ('info', 'warning', 'critical')),
  constraint city_events_status_valido check (status in (
    'draft', 'scheduled', 'active', 'awaiting_confirmation', 'resolved', 'cancelled'
  )),
  -- Regra 9 do plano: toda resolucao tem autor e data.
  constraint city_events_resolvido_tem_desfecho check (
    status <> 'resolved' or (resolved_at is not null and resolved_by is not null)
  ),
  constraint city_events_titulo_nao_vazio check (length(btrim(title)) > 0)
);

comment on table public.city_events is
  'Acontecimentos da cidade (Trombone Agora). Um por regiao, nunca uma copia por rua.';
comment on column public.city_events.confirmation_cycle is
  'Numero de resolucoes ja anunciadas. Reabrir incrementa; a enquete da comunidade e por ciclo.';
comment on column public.city_events.overdue_notified_at is
  'Quando o responsavel foi avisado de previsao vencida. Torna a varredura idempotente.';

create index if not exists city_events_cidade_status_idx
  on public.city_events (city_id, status, started_at desc);

create index if not exists city_events_previsao_vencida_idx
  on public.city_events (estimated_end_at)
  where status = 'active' and estimated_end_at is not null;

create index if not exists city_events_resolvidos_idx
  on public.city_events (city_id, resolved_at desc)
  where status = 'resolved';

-- ── 1.2 Regioes atingidas ───────────────────────────────────────────────────
--
-- Regra 3 do plano: um acontecimento regional NAO e duplicado por rua. A rua
-- descobre que esta atingida por consulta — bairro dela dentro das areas, ou
-- evento de cidade inteira — e nao por uma copia da linha.
--
-- POR QUE SO city / neighborhood / street
--
-- O plano lista tambem `district` e `polygon`. Nenhum dos dois tem tabela neste
-- banco. Aceita-los no CHECK criaria area que nada resolve: o evento existiria,
-- ninguem seria encontrado, e o silencio pareceria "ninguem acompanha a
-- regiao". Entram quando houver o que apontar.
--
-- `area_id` e uuid porque `bairros.id` e `pavement_streets.id` sao uuid. A
-- cidade nao precisa de id proprio aqui: ela ja esta em city_events.city_id, e
-- guardar de novo abriria a chance de os dois divergirem.

create table if not exists public.city_event_areas (
  id            bigint generated by default as identity primary key,
  city_event_id bigint not null references public.city_events(id) on delete cascade,
  area_type     text not null,
  area_id       uuid,
  created_at    timestamptz not null default now(),

  constraint city_event_areas_tipo_valido check (area_type in ('city', 'neighborhood', 'street')),
  constraint city_event_areas_id_conforme_tipo check (
    (area_type = 'city' and area_id is null)
    or (area_type <> 'city' and area_id is not null)
  )
);

comment on table public.city_event_areas is
  'Onde o acontecimento pega. area_type=city vale a cidade inteira do evento e deixa area_id nulo.';

create unique index if not exists city_event_areas_sem_repeticao
  on public.city_event_areas
     (city_event_id, area_type, coalesce(area_id, '00000000-0000-0000-0000-000000000000'::uuid));

create index if not exists city_event_areas_por_area_idx
  on public.city_event_areas (area_type, area_id);

-- ── 1.3 Linha do tempo ──────────────────────────────────────────────────────
--
-- Regra 10: o historico nunca e apagado quando o status muda. Toda transicao
-- escreve uma linha aqui, e nenhuma tela reconstroi a historia a partir do
-- estado atual — porque o estado atual nao sabe que a previsao ja foi 18h.
--
-- A tabela e append-only por RLS: existe policy de insert, nao existe de update
-- nem de delete. Nao e descuido; e a regra 10 escrita como permissao.

create table if not exists public.city_event_updates (
  id                   bigint generated by default as identity primary key,
  city_event_id        bigint not null references public.city_events(id) on delete cascade,

  type                 text not null,
  message              text,

  old_estimated_end_at timestamptz,
  new_estimated_end_at timestamptz,

  created_by           uuid references public.profiles(id) on delete set null,
  created_by_role      text,

  created_at           timestamptz not null default now(),

  constraint city_event_updates_tipo_valido check (type in (
    'created', 'progress', 'extended', 'resolved', 'reopened', 'cancelled', 'community_divergence'
  ))
);

comment on table public.city_event_updates is
  'Historia do acontecimento. Append-only: ha policy de insert, nao ha de update nem delete.';

create index if not exists city_event_updates_linha_do_tempo_idx
  on public.city_event_updates (city_event_id, created_at desc);

-- ── 1.4 Confirmacao da comunidade ───────────────────────────────────────────

