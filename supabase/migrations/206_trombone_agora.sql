-- PARTE 3 — QUEM E AVISADO
-- ═══════════════════════════════════════════════════════════════════════════

-- A audiencia de um acontecimento.
--
-- A REGRA DE ALCANCE, EM UMA FRASE: quem acompanha uma area que o evento toca,
-- COM a chave daquele tipo ligada.
--
-- "Toca" e o que a secao 11 do plano descreve e o que evita a copia por rua:
--
--   * segue a CIDADE  -> so quando o evento e de cidade inteira;
--   * segue um BAIRRO -> quando o bairro esta nas areas, quando uma rua listada
--                        fica nele, ou quando o evento e de cidade inteira;
--   * segue uma RUA   -> quando a rua esta listada, quando o bairro dela esta,
--                        ou quando o evento e de cidade inteira.
--
-- O caminho "rua -> bairro" e o que faz "falta d'agua no Morada Nobre" chegar a
-- quem acompanha so a propria rua, sem nenhuma linha por rua ter sido criada.
create or replace function public.city_event_audience(p_event_id bigint)
returns table (user_id uuid)
language sql
stable
security definer
set search_path = public
as $$
  with evento as (
    select e.id, e.city_id, e.type from public.city_events e where e.id = p_event_id
  ),
  areas as (
    select a.area_type, a.area_id from public.city_event_areas a where a.city_event_id = p_event_id
  ),
  cidade_inteira as (
    select exists (select 1 from areas where area_type = 'city') as sim
  ),
  bairros_atingidos as (
    select area_id as bairro_id from areas where area_type = 'neighborhood'
    union
    select s.bairro_id
      from public.pavement_streets s
      join areas a on a.area_type = 'street' and a.area_id = s.id
     where s.bairro_id is not null
  )
  select distinct f.user_id
  from public.user_area_follows f
  cross join evento e
  cross join cidade_inteira ci
  where
    -- A chave daquele tipo esta ligada para esta area?
    case e.type
      when 'water_outage'     then f.water_alerts
      when 'power_outage'     then f.power_alerts
      when 'road_block'       then f.traffic_alerts
      when 'traffic'          then f.traffic_alerts
      when 'public_transport' then f.traffic_alerts
      when 'construction'     then f.works_alerts
      when 'event'            then f.events_alerts
      when 'public_notice'    then f.public_notice_alerts
      else f.critical_alerts
    end
    and (
      (f.area_type = 'city' and f.city_id = e.city_id and ci.sim)

      or (f.area_type = 'neighborhood' and (
            f.area_id in (select bairro_id from bairros_atingidos)
            or (ci.sim and exists (
                 select 1 from public.bairros b where b.id = f.area_id and b.city_id = e.city_id
               ))
         ))

      or (f.area_type = 'street' and (
            f.area_id in (select area_id from areas where area_type = 'street')
            or exists (
                 select 1 from public.pavement_streets s
                 where s.id = f.area_id
                   and (
                     s.bairro_id in (select bairro_id from bairros_atingidos)
                     or (ci.sim and s.city_id = e.city_id)
                   )
               )
         ))
    );
$$;

-- Quem responde pela cidade: admin, master e embaixador ativo.
--
-- Quando o embaixador tem bairros designados, so entra se algum dos bairros
-- dele estiver no evento — senao todo embaixador da cidade seria acordado por
-- toda previsao vencida em qualquer bairro, que e o ruido que a designacao
-- existe para cortar.
create or replace function public.city_event_managers(p_event_id bigint)
returns table (user_id uuid)
language sql
stable
security definer
set search_path = public
as $$
  with evento as (
    select e.id, e.city_id from public.city_events e where e.id = p_event_id
  ),
  areas as (
    select a.area_type, a.area_id from public.city_event_areas a where a.city_event_id = p_event_id
  ),
  cidade_inteira as (
    select exists (select 1 from areas where area_type = 'city') as sim
  ),
  bairros_atingidos as (
    select area_id as bairro_id from areas where area_type = 'neighborhood'
    union
    select s.bairro_id
      from public.pavement_streets s
      join areas a on a.area_type = 'street' and a.area_id = s.id
     where s.bairro_id is not null
  )
  select distinct p.id
  from public.profiles p
  cross join evento e
  cross join cidade_inteira ci
  where p.is_admin = true
     or p.is_master = true
     or (
       exists (
         select 1 from public.ambassador_cities ac
         where ac.user_id = p.id and ac.city_id = e.city_id and ac.status = 'active'
       )
       and (
         not exists (
           select 1 from public.ambassador_areas aa
           where aa.user_id = p.id and aa.city_id = e.city_id
         )
         or ci.sim
         or exists (
           select 1 from public.ambassador_areas aa
           where aa.user_id = p.id and aa.city_id = e.city_id
             and aa.area_id in (select bairro_id from bairros_atingidos)
         )
       )
     );
$$;

