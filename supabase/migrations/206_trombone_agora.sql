-- Detecta a divergencia da secao 16 e acorda quem responde pela cidade.
--
-- O PISO DE 10 RESPOSTAS NAO E ARBITRARIO
--
-- Sem piso, as duas primeiras respostas decidem: um "ainda nao" contra um "sim"
-- da 50% e reabriria o evento com uma pessoa discordando. Dez e o menor numero
-- em que a maioria simples ainda diz alguma coisa sobre o bairro, e nao sobre
-- quem abriu o app primeiro.
--
-- E avisa UMA vez por ciclo: o gestor recebe "a comunidade discorda", decide, e
-- se decidir manter encerrado nao e perseguido a cada resposta nova.
create or replace function public.check_city_event_divergence(p_event_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event   public.city_events;
  v_sim     integer;
  v_nao     integer;
  v_total   integer;
  v_pct     integer;
begin
  select * into v_event from public.city_events where id = p_event_id;
  if not found then return false; end if;

  select
    count(*) filter (where status = 'resolved'),
    count(*) filter (where status = 'not_resolved')
  into v_sim, v_nao
  from public.city_event_confirmations
  where city_event_id = p_event_id and cycle = v_event.confirmation_cycle;

  v_total := v_sim + v_nao;
  if v_total < 10 or v_nao <= v_sim then return false; end if;

  if exists (
    select 1 from public.city_event_updates
    where city_event_id = p_event_id and type = 'community_divergence'
      and created_at > coalesce(v_event.resolved_at, v_event.created_at)
  ) then
    return false;
  end if;

  v_pct := round(100.0 * v_nao / v_total);

  insert into public.city_event_updates (city_event_id, type, message)
  values (
    p_event_id, 'community_divergence',
    v_pct || '% de ' || v_total || ' respostas dizem que ainda nao normalizou.'
  );

  perform public.notify_city_event_managers(
    p_event_id, 'city_event_divergence', 'Possivel problema persistente',
    v_pct || '% dos moradores que responderam dizem que "' || v_event.title ||
    '" ainda nao foi normalizado.'
  );

  return true;
end;
$$;

-- ── 4.2 A varredura da previsao ─────────────────────────────────────────────
--
-- Secao 12 do plano. Faz duas coisas, e nenhuma delas encerra evento (regra 4):
--
--   1. `scheduled` cujo inicio ja chegou vira `active` e avisa a audiencia;
--   2. `active` com previsao vencida vira `awaiting_confirmation` e acorda quem
--      responde pela cidade — que decide entre prorrogar e resolver.
--
-- POR QUE E IDEMPOTENTE, E POR QUE ISSO IMPORTA
--
-- Nao ha garantia de agendador neste projeto (pg_cron pode nao estar ligado no
-- plano do Supabase). Entao a funcao tambem e chamada pelo app quando um gestor
-- abre o Agora. Chamada tres vezes em um minuto, ela avisa uma so: quem ja foi
-- avisado tem `overdue_notified_at` preenchido.
create or replace function public.sweep_city_events()
returns table (publicados integer, vencidos integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id          bigint;
  v_publicados  integer := 0;
  v_vencidos    integer := 0;
  v_titulo      text;
begin
  for v_id, v_titulo in
    select id, title from public.city_events
    where status = 'scheduled' and started_at <= now()
  loop
    update public.city_events set status = 'active' where id = v_id;
    perform public.notify_city_event_audience(
      v_id, 'city_event', v_titulo, 'Comecou agora. Toque para ver a situacao.'
    );
    v_publicados := v_publicados + 1;
  end loop;

  for v_id, v_titulo in
    select id, title from public.city_events
    where status = 'active'
      and estimated_end_at is not null
      and estimated_end_at <= now()
      and overdue_notified_at is null
  loop
    update public.city_events set
      status = 'awaiting_confirmation',
      overdue_notified_at = now()
    where id = v_id;

    perform public.notify_city_event_managers(
      v_id, 'city_event_check', 'Verificar acontecimento',
      'A previsao de "' || v_titulo || '" terminou. O problema ja foi resolvido?'
    );
    v_vencidos := v_vencidos + 1;
  end loop;

  return query select v_publicados, v_vencidos;
end;
$$;

-- Agenda a varredura se o banco tiver pg_cron. Sem a extensao, o app chama a
-- funcao sozinho — a varredura ser idempotente e o que permite as duas coisas
-- coexistirem sem duplicar aviso.
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.unschedule('sweep_city_events');
  end if;
exception when others then
  -- Nao havia agendamento anterior. E o caso normal na primeira execucao.
  null;
end $$;

do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('sweep_city_events', '*/5 * * * *', 'select public.sweep_city_events();');
  end if;
exception when others then
  raise notice 'pg_cron indisponivel; a varredura fica por conta do app.';
end $$;

