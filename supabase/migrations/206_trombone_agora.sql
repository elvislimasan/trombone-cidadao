-- PARTE 4 — ESCRITA (as RPCs)
-- ═══════════════════════════════════════════════════════════════════════════
--
-- POR QUE A TELA NAO GRAVA DIRETO
--
-- Existem policies de escrita para gestor (parte 6), e elas sao a autoridade.
-- Mas todo caminho do app passa por estas funcoes, porque cada transicao tem um
-- efeito colateral que a regra 8 e a 10 do plano exigem: escrever a linha do
-- tempo e avisar quem acompanha. Um UPDATE direto em `status` produziria um
-- evento resolvido sem nenhum registro de quem resolveu e sem ninguem saber.

-- Grava as areas de um evento a partir do jsonb [{area_type, area_id}].
-- A CIDADE DA AREA TEM QUE SER A CIDADE DO EVENTO
--
-- Sem esta checagem, um bairro de OUTRA cidade entrava na lista de areas e
-- `city_event_audience` — que casa o seguidor pelo id do bairro, nao pela
-- cidade — mandava "falta d'agua no Morada Nobre" para quem acompanha um
-- bairro homonimo a 600 km.
--
-- `city_event_scope_ok` nao pegava isso: ela devolve `true` na hora para admin
-- e master, e tambem para o embaixador que nao tem bairro designado — que e a
-- configuracao da maioria. Sobrava so o seletor da tela filtrando por cidade,
-- e tela nao e autoridade: a RPC esta aberta a `authenticated`.
--
-- Area inexistente cai no mesmo erro de proposito. `coalesce(b.city_id,
-- s.city_id)` vem nulo quando o uuid nao existe, e `is distinct from` trata
-- nulo como diferente — um id inventado nunca vira area silenciosa.
create or replace function public.set_city_event_areas(p_event_id bigint, p_areas jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_city_id bigint;
  v_fora    integer;
begin
  select city_id into v_city_id from public.city_events where id = p_event_id;
  if v_city_id is null then
    raise exception 'Acontecimento nao encontrado.' using errcode = 'P0002';
  end if;

  select count(*) into v_fora
  from jsonb_array_elements(coalesce(p_areas, '[]'::jsonb)) as t(item)
  left join public.bairros b
    on t.item->>'area_type' = 'neighborhood'
   and b.id = nullif(t.item->>'area_id', '')::uuid
  left join public.pavement_streets s
    on t.item->>'area_type' = 'street'
   and s.id = nullif(t.item->>'area_id', '')::uuid
  where t.item->>'area_type' <> 'city'
    and coalesce(b.city_id, s.city_id) is distinct from v_city_id;

  if v_fora > 0 then
    raise exception 'Ha % area(s) de outra cidade ou inexistente(s) na lista.', v_fora
      using errcode = '42501';
  end if;

  delete from public.city_event_areas where city_event_id = p_event_id;

  insert into public.city_event_areas (city_event_id, area_type, area_id)
  select
    p_event_id,
    t.item->>'area_type',
    case when t.item->>'area_type' = 'city' then null
         else nullif(t.item->>'area_id', '')::uuid end
  from jsonb_array_elements(coalesce(p_areas, '[]'::jsonb)) as t(item)
  on conflict do nothing;
end;
$$;

create or replace function public.create_city_event(
  p_city_id          bigint,
  p_type             text,
  p_title            text,
  p_areas            jsonb,
  p_description      text default null,
  p_severity         text default 'warning',
  p_started_at       timestamptz default null,
  p_estimated_end_at timestamptz default null,
  p_source_name      text default null,
  p_source_url       text default null,
  p_notify           boolean default true,
  p_status           text default 'active'
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user    uuid := auth.uid();
  v_role    text;
  v_id      bigint;
  v_inicio  timestamptz := coalesce(p_started_at, now());
  v_status  text := coalesce(p_status, 'active');
begin
  v_role := public.city_event_role(v_user, p_city_id);
  if v_role is null then
    raise exception 'Sem permissao para criar acontecimentos nesta cidade.' using errcode = '42501';
  end if;

  if jsonb_array_length(coalesce(p_areas, '[]'::jsonb)) = 0 then
    raise exception 'Escolha ao menos uma area atingida.' using errcode = '22023';
  end if;

  if not public.city_event_scope_ok(v_user, p_city_id, p_areas) then
    raise exception 'Alguma das areas escolhidas esta fora do seu escopo.' using errcode = '42501';
  end if;

  -- Um evento com inicio no futuro e `scheduled`, nao `active`: dizer "em
  -- andamento" as 10h sobre algo que comeca as 14h e informacao errada, e o
  -- push sairia com previsao que ainda nao vale.
  if v_status = 'active' and v_inicio > now() then
    v_status := 'scheduled';
  end if;

  if p_estimated_end_at is not null and p_estimated_end_at <= v_inicio then
    raise exception 'A previsao precisa ser depois do inicio.' using errcode = '22023';
  end if;

  insert into public.city_events (
    city_id, type, title, description, severity, status,
    started_at, estimated_end_at, source_name, source_url,
    created_by, created_by_role
  ) values (
    p_city_id, p_type, btrim(p_title), nullif(btrim(coalesce(p_description, '')), ''),
    coalesce(p_severity, 'warning'), v_status,
    v_inicio, p_estimated_end_at,
    nullif(btrim(coalesce(p_source_name, '')), ''), nullif(btrim(coalesce(p_source_url, '')), ''),
    v_user, v_role
  )
  returning id into v_id;

  perform public.set_city_event_areas(v_id, p_areas);

  insert into public.city_event_updates (city_event_id, type, message, new_estimated_end_at, created_by, created_by_role)
  values (v_id, 'created', nullif(btrim(coalesce(p_description, '')), ''), p_estimated_end_at, v_user, v_role);

  -- Rascunho nao avisa ninguem: e o unico estado em que o texto ainda pode
  -- estar errado de proposito.
  if p_notify and v_status = 'active' then
    perform public.notify_city_event_audience(
      v_id, 'city_event', btrim(p_title),
      coalesce(nullif(btrim(coalesce(p_description, '')), ''), 'Toque para ver a situacao.'),
      v_user
    );
  end if;

  return v_id;
end;
$$;

