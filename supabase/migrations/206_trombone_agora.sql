-- ── 4.1 A confirmacao da comunidade ─────────────────────────────────────────

create or replace function public.confirm_city_event(p_event_id bigint, p_status text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user  uuid := auth.uid();
  v_event public.city_events;
begin
  if v_user is null then
    raise exception 'Entre na sua conta para responder.' using errcode = '42501';
  end if;
  if p_status not in ('resolved', 'not_resolved') then
    raise exception 'Resposta invalida.' using errcode = '22023';
  end if;

  select * into v_event from public.city_events where id = p_event_id;
  if not found then
