  end if;

  insert into public.city_event_confirmations (city_event_id, user_id, cycle, status)
  values (p_event_id, v_user, v_event.confirmation_cycle, p_status)
  on conflict (city_event_id, user_id, cycle)
  do update set status = excluded.status, updated_at = now();

  perform public.check_city_event_divergence(p_event_id);
