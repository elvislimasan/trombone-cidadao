-- ── 1.5 Acompanhamento de area ──────────────────────────────────────────────
--
-- POR QUE UMA PREFERENCIA A MAIS QUE O PLANO PEDE
--
-- O plano lista seis chaves (agua, energia, transito, obras, eventos,
-- comunicados) e onze tipos. Sobram `weather`, `health` e `other`. Encaixa-los
-- em `events_alerts` faria "alerta de chuva forte" ser desligado por quem so
-- nao queria saber de feira livre — que e o unico dos tres que da para perder
-- sem consequencia.
--
-- `critical_alerts` cobre os tres e vem ligado. Continua desligavel: ninguem e
-- obrigado a nada. Mas exige um gesto proprio.

create table if not exists public.user_area_follows (
  id                   bigint generated by default as identity primary key,
  user_id              uuid not null references public.profiles(id) on delete cascade,

  area_type            text not null,
  area_id              uuid,
  city_id              bigint references public.cities(id) on delete cascade,

  water_alerts         boolean not null default true,
  power_alerts         boolean not null default true,
  traffic_alerts       boolean not null default true,
  works_alerts         boolean not null default true,
  events_alerts        boolean not null default true,
  public_notice_alerts boolean not null default true,
  critical_alerts      boolean not null default true,

  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),

  constraint user_area_follows_tipo_valido check (area_type in ('city', 'neighborhood', 'street')),
  constraint user_area_follows_id_conforme_tipo check (
    (area_type = 'city' and area_id is null and city_id is not null)
    or (area_type <> 'city' and area_id is not null)
  )
);

comment on table public.user_area_follows is
  'Quem acompanha qual rua, bairro ou cidade, e com quais alertas ligados.';

create unique index if not exists user_area_follows_uma_por_cidade
  on public.user_area_follows (user_id, city_id) where area_type = 'city';

create unique index if not exists user_area_follows_uma_por_area
  on public.user_area_follows (user_id, area_type, area_id) where area_type <> 'city';

create index if not exists user_area_follows_por_area_idx
  on public.user_area_follows (area_type, area_id);

-- ── 1.6 Escopo do embaixador por bairro ─────────────────────────────────────
--
-- POR QUE ESTA TABELA NAO SUBSTITUI `ambassador_cities`
--
-- O plano (secao 24) sugere `ambassador_areas` como O escopo do embaixador.
-- Hoje quem responde isso e `ambassador_cities` + `is_ambassador_of`, usada em
-- pavimentacao, servicos, obras e moderacao. Trocar a autoridade quebraria as
-- quatro; manter as duas como autoridades iguais faria elas divergirem.
--
-- Entao esta tabela nao decide nada sozinha: ela apenas ESTREITA. Sem nenhuma
-- linha, o embaixador continua com a cidade inteira, exatamente como hoje. Com
-- linhas, so publica nos bairros listados. E aditiva por construcao — o
-- embaixador que ninguem configurou nao muda de comportamento.

create table if not exists public.ambassador_areas (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references public.profiles(id) on delete cascade,
  city_id    bigint not null references public.cities(id) on delete cascade,
  area_type  text not null default 'neighborhood',
  area_id    uuid not null,
  created_at timestamptz not null default now(),

  constraint ambassador_areas_tipo_valido check (area_type in ('neighborhood'))
);

comment on table public.ambassador_areas is
  'Estreita o escopo de um embaixador a bairros. Sem linhas, vale a cidade inteira de ambassador_cities.';

create unique index if not exists ambassador_areas_sem_repeticao
  on public.ambassador_areas (user_id, area_type, area_id);

