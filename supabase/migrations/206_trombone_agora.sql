-- Rotulo das areas de um evento, como jsonb.
create or replace function public.city_event_areas_json(p_event_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(jsonb_agg(item order by ordem, rotulo), '[]'::jsonb)
  from (
    select
      1 as ordem,
      c.name as rotulo,
      jsonb_build_object('area_type', 'city', 'area_id', null, 'label', c.name) as item
    from public.city_event_areas a
    join public.city_events e on e.id = a.city_event_id
    join public.cities c on c.id = e.city_id
    where a.city_event_id = p_event_id and a.area_type = 'city'

    union all

    select 2, b.name,
      jsonb_build_object('area_type', 'neighborhood', 'area_id', b.id, 'label', b.name)
    from public.city_event_areas a
    join public.bairros b on b.id = a.area_id
    where a.city_event_id = p_event_id and a.area_type = 'neighborhood'

    union all

    select 3, s.name,
      jsonb_build_object('area_type', 'street', 'area_id', s.id, 'label', s.name)
    from public.city_event_areas a
    join public.pavement_streets s on s.id = a.area_id
    where a.city_event_id = p_event_id and a.area_type = 'street'
  ) t;
$$;

-- A lista do Agora.
create or replace function public.get_city_events(
  p_city_id  bigint,
  p_statuses text[] default array['active', 'awaiting_confirmation', 'scheduled'],
  p_types    text[] default null,
  p_limit    integer default 50
)
returns table (
  id                 bigint,
  city_id            bigint,
  type               text,
  title              text,
  description        text,
  severity           text,
  status             text,
  started_at         timestamptz,
  estimated_end_at   timestamptz,
  resolved_at        timestamptz,
  source_name        text,
  source_url         text,
  confirmation_cycle integer,
  areas              jsonb,
  updates_count      integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    e.id, e.city_id, e.type, e.title, e.description, e.severity, e.status,
    e.started_at, e.estimated_end_at, e.resolved_at, e.source_name, e.source_url,
    e.confirmation_cycle,
    public.city_event_areas_json(e.id),
    (select count(*)::integer from public.city_event_updates u where u.city_event_id = e.id)
  from public.city_events e
  where e.city_id = p_city_id
    and e.status = any (coalesce(p_statuses, array['active', 'awaiting_confirmation', 'scheduled']))
    and (p_types is null or e.type = any (p_types))
    -- Rascunho so aparece para quem pode gerir. Um rascunho publico seria um
    -- alerta que a cidade le antes de o texto estar certo.
    and (e.status <> 'draft' or public.can_manage_city_events(auth.uid(), e.city_id))
  order by
    case e.status when 'active' then 0 when 'awaiting_confirmation' then 1
                  when 'scheduled' then 2 else 3 end,
    coalesce(e.resolved_at, e.started_at) desc
  limit greatest(1, least(coalesce(p_limit, 50), 200));
$$;

-- Um acontecimento com tudo o que a tela de detalhe mostra, numa ida so.
create or replace function public.get_city_event(p_event_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id',                 e.id,
    'city_id',            e.city_id,
    'city_name',          c.name,
    'type',               e.type,
    'title',              e.title,
    'description',        e.description,
    'severity',           e.severity,
    'status',             e.status,
    'started_at',         e.started_at,
    'estimated_end_at',   e.estimated_end_at,
    'resolved_at',        e.resolved_at,
    'source_name',        e.source_name,
    'source_url',         e.source_url,
    'confirmation_cycle', e.confirmation_cycle,
    'can_manage',         public.can_manage_city_events(auth.uid(), e.city_id),
    'areas',              public.city_event_areas_json(e.id),
    'updates', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', u.id, 'type', u.type, 'message', u.message,
        'old_estimated_end_at', u.old_estimated_end_at,
        'new_estimated_end_at', u.new_estimated_end_at,
        'created_at', u.created_at,
        'created_by_role', u.created_by_role,
        'author_name', p.name
      ) order by u.created_at asc), '[]'::jsonb)
      from public.city_event_updates u
      left join public.profiles p on p.id = u.created_by
      where u.city_event_id = e.id
    ),
    'confirmations', (
      select jsonb_build_object(
        'resolved',     count(*) filter (where cf.status = 'resolved'),
        'not_resolved', count(*) filter (where cf.status = 'not_resolved'),
        'last_at',      max(cf.updated_at)
      )
      from public.city_event_confirmations cf
      where cf.city_event_id = e.id and cf.cycle = e.confirmation_cycle
    ),
    'my_confirmation', (
      select cf.status from public.city_event_confirmations cf
      where cf.city_event_id = e.id and cf.cycle = e.confirmation_cycle and cf.user_id = auth.uid()
    )
  )
  from public.city_events e
  join public.cities c on c.id = e.city_id
  where e.id = p_event_id
    and (e.status <> 'draft' or public.can_manage_city_events(auth.uid(), e.city_id));
$$;

-- Os acontecimentos que pegam numa rua. E o que Minha Rua consulta.
--
-- A rua e atingida pelo bairro dela ou pela cidade inteira — nunca por uma
-- linha propria. E a regra 3 do plano lida de tras para a frente.
create or replace function public.get_street_city_events(p_street_id uuid)
returns table (
  id               bigint,
  type             text,
  title            text,
  description      text,
  severity         text,
  status           text,
  started_at       timestamptz,
  estimated_end_at timestamptz,
  resolved_at      timestamptz,
  areas            jsonb
)
language sql
stable
security definer
set search_path = public
as $$
  with rua as (
    select s.id, s.bairro_id, s.city_id from public.pavement_streets s where s.id = p_street_id
  )
  select
    e.id, e.type, e.title, e.description, e.severity, e.status,
    e.started_at, e.estimated_end_at, e.resolved_at,
    public.city_event_areas_json(e.id)
  from public.city_events e
  join rua r on r.city_id = e.city_id
  where e.status in ('active', 'awaiting_confirmation')
    and exists (
      select 1 from public.city_event_areas a
      where a.city_event_id = e.id
        and (
          a.area_type = 'city'
          or (a.area_type = 'street' and a.area_id = r.id)
          or (a.area_type = 'neighborhood' and a.area_id = r.bairro_id)
        )
    )
  order by e.started_at desc;
$$;

-- O resumo do Trombone Impacto para uma cidade num periodo.
--
-- Le so o que o Agora produz. Broncas, obras e participacao ja tem contadores
-- proprios em `get_mission_counters` (migracao 198) — repetir a conta aqui
-- criaria dois numeros para a mesma pergunta.
create or replace function public.get_city_events_impact(
  p_city_id bigint,
  p_since   timestamptz default (now() - interval '30 days')
)
returns table (
  publicados      integer,
  resolvidos      integer,
  em_andamento    integer,
  confirmacoes    integer,
  participantes   integer,
  minutos_medios  integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    (select count(*)::integer from public.city_events e
      where e.city_id = p_city_id and e.started_at >= p_since and e.status <> 'draft'),
    (select count(*)::integer from public.city_events e
      where e.city_id = p_city_id and e.resolved_at >= p_since),
    (select count(*)::integer from public.city_events e
      where e.city_id = p_city_id and e.status in ('active', 'awaiting_confirmation')),
    (select count(*)::integer from public.city_event_confirmations cf
      join public.city_events e on e.id = cf.city_event_id
      where e.city_id = p_city_id and cf.created_at >= p_since),
    (select count(distinct cf.user_id)::integer from public.city_event_confirmations cf
      join public.city_events e on e.id = cf.city_event_id
      where e.city_id = p_city_id and cf.created_at >= p_since),
    (select coalesce(round(avg(extract(epoch from (e.resolved_at - e.started_at)) / 60))::integer, 0)
      from public.city_events e
      where e.city_id = p_city_id and e.resolved_at >= p_since);
$$;

