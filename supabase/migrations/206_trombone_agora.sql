-- 206_trombone_agora.sql
--
-- Trombone Agora: acontecimentos da cidade, com previsao, prorrogacao,
-- resolucao e confirmacao da comunidade. Mais o acompanhamento de area que faz
-- Minha Rua saber quando algo esta acontecendo na regiao de quem le.
--
-- POR QUE ACONTECIMENTO, E NAO NOTIFICACAO
--
-- Um push e um disparo: existe no instante em que sai e some. "Falta d'agua no
-- Morada Nobre" nao e um instante — comeca, tem previsao, e prorrogada, volta,
-- e depois alguem precisa dizer se voltou mesmo. Modelado como notificacao, o
-- app so consegue responder "algo foi avisado"; modelado como linha com estado,
-- responde "o que esta acontecendo agora, desde quando e ate quando".
--
-- O push continua existindo — mas como CONSEQUENCIA da linha, nao como o dado.
-- Cada acontecimento novo, prorrogacao e resolucao insere em `notifications`, e
-- o webhook que ja existe leva ao aparelho. Nenhuma Edge Function nova: o campo
-- `link` da notificacao (`/agora/438`) ja e o que send-push-notification usa
-- para montar o destino do toque (ver `computeTargetUrl` la).
--
-- POR QUE `city_id` E NAO `tenant_id`
--
-- O plano fala em tenant. Neste projeto o inquilino E a cidade desde a
-- nacionalizacao (migracoes 144, 151, 154, 158): `cities` e a raiz de escopo,
-- `ambassador_cities` diz quem manda em qual, e `is_ambassador_of` ja responde
-- a pergunta. Um `tenant_id` paralelo seria uma segunda autoridade de escopo,
-- divergindo em silencio da primeira.
--
-- AS POLICIES ESTAO AQUI, DE PROPOSITO
--
-- As migracoes 202, 203 e 204 registram o problema: neste projeto as policies
-- moram no painel do Supabase e nao no git, entao toda tabela nova vira regra
-- invisivel ao codigo. Elas evitaram criar tabela por isso. Aqui nao da para
-- evitar — um acontecimento nao cabe numa coluna — entao vale a outra metade da
-- mesma preocupacao: TODA policy destas seis tabelas esta escrita neste
-- arquivo, versionada e revisavel em diff.

-- ═══════════════════════════════════════════════════════════════════════════
-- PARTE 1 — TABELAS
